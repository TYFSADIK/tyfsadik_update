#!/usr/bin/env python3
"""Generate docs/SITE-INVENTORY.md: per-page SEO/content inventory for the whole site."""
import re, json, glob, os, collections
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'docs' / 'SITE-INVENTORY.md'

files = sorted(f for f in glob.glob(str(ROOT / '**/*.html'), recursive=True) if '/.' not in f[len(str(ROOT))+1:])
rel = [str(Path(f).relative_to(ROOT)) for f in files]

# inbound link counts
inbound = collections.Counter()
for f in rel:
    txt = (ROOT / f).read_text(encoding='utf-8')
    for m in re.finditer(r'href="([^"#][^"]*)"', txt):
        href = m.group(1).split('#')[0]
        if href.startswith(('http', 'mailto:', 'tel:', 'data:')):
            continue
        t = os.path.normpath(os.path.join(os.path.dirname(f), href))
        if t != f:
            inbound[t] += 1

rows = []
for f in rel:
    txt = (ROOT / f).read_text(encoding='utf-8')
    title = (re.search(r'<title>(.*?)</title>', txt, re.S) or [None, ''])[1].strip()
    desc_m = re.search(r'<meta name="description" content="([^"]*)"', txt)
    desc = desc_m.group(1) if desc_m else ''
    h1_m = re.search(r'<h1[^>]*>(.*?)</h1>', txt, re.S)
    h1 = re.sub(r'<[^>]+>', '', h1_m.group(1)).strip() if h1_m else ''
    can_m = re.search(r'rel="canonical" href="([^"]*)"', txt)
    can = can_m.group(1) if can_m else ''
    body = re.sub(r'<script.*?</script>|<style.*?</style>', '', txt, flags=re.S)
    words = len(re.sub(r'<[^>]+>', ' ', body).split())
    out_links = len(set(re.findall(r'href="https?://(?!tyfsadik\.org)[^"]+"', txt)))
    imgs = re.findall(r'<img\b[^>]*>', txt)
    imgs_noalt = sum(1 for i in imgs if 'alt=' not in i)
    jsonld = len(re.findall(r'application/ld\+json', txt))
    # JS-rendered sections: empty containers filled from JS
    js_sections = []
    for marker, name in [('id="recent-labs"', 'Latest Labs'), ('id="featured-projects"', 'Featured Projects'),
                         ('id="stats-row"', 'At a Glance counters'), ('id="project-grid"', 'Project grid'),
                         ('id="lab-grid"', 'Lab grid')]:
        if marker in txt:
            container = re.search(re.escape(marker) + r'[^>]*>(.*?)</div>', txt, re.S)
            inner = container.group(1).strip() if container else ''
            js_sections.append(name + ('' if not inner else ' (has static content)'))
    noindex = 'noindex' in txt
    rows.append((f, title, len(desc), h1[:60], can.replace('https://tyfsadik.org', '') or '/', words,
                 inbound.get(f, 0), out_links, len(imgs), imgs_noalt, jsonld,
                 ', '.join(js_sections) if js_sections else '-', 'noindex' if noindex else ''))

lines = [
    '# Site Inventory',
    '',
    'Generated by `.tools/site_inventory.py`. Regenerate after structural changes.',
    '',
    f'Pages: {len(rows)}',
    '',
    '| Page | Title (chars) | Desc len | H1 | Canonical | Words | Inbound | Outbound ext | Imgs (no alt) | JSON-LD | JS-rendered sections | Notes |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|',
]
for r in rows:
    lines.append('| ' + ' | '.join(str(x).replace('|', '/') for x in r) + ' |')

OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('wrote', OUT, len(rows), 'pages')
